create or replace function public.prevent_agent_ledger_mutation()
returns trigger language plpgsql set search_path = public as $$
begin
  raise exception 'Registros de auditoria do agente sao imutaveis';
end;
$$;

drop trigger if exists trg_agent_events_immutable on public.agent_events;
create trigger trg_agent_events_immutable before update or delete on public.agent_events
for each row execute function public.prevent_agent_ledger_mutation();
drop trigger if exists trg_agent_audit_immutable on public.agent_audit_logs;
create trigger trg_agent_audit_immutable before update or delete on public.agent_audit_logs
for each row execute function public.prevent_agent_ledger_mutation();

create or replace function public.enqueue_agent_task(
  p_client_id bigint,
  p_task_type text,
  p_priority text,
  p_due_at timestamptz,
  p_payload jsonb,
  p_idempotency_key text
) returns public.agent_tasks
language plpgsql security invoker set search_path = public as $$
declare result public.agent_tasks;
begin
  if p_idempotency_key is null or length(trim(p_idempotency_key)) < 8 then
    raise exception 'Chave de idempotencia invalida';
  end if;
  insert into public.agent_tasks(client_id, task_type, priority, due_at, payload, idempotency_key)
  values(p_client_id, p_task_type, coalesce(p_priority, 'P3'), coalesce(p_due_at, now()), coalesce(p_payload, '{}'::jsonb), p_idempotency_key)
  on conflict (idempotency_key) do update set idempotency_key = excluded.idempotency_key
  returning * into result;
  return result;
end;
$$;

