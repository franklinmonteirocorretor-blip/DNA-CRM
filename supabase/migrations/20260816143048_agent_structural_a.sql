create table if not exists public.agent_tasks (
  id bigint generated by default as identity primary key,
  client_id bigint references public.clients(id) on delete cascade,
  task_type text not null,
  priority text not null default 'P3' check (priority in ('P0','P1','P2','P3','P4','P5')),
  status text not null default 'pending' check (status in ('pending','running','completed','failed','cancelled')),
  due_at timestamptz not null default now(),
  payload jsonb not null default '{}'::jsonb,
  attempts integer not null default 0 check (attempts >= 0),
  max_attempts integer not null default 3 check (max_attempts > 0),
  idempotency_key text not null unique,
  correlation_id uuid not null default gen_random_uuid(),
  last_error text,
  locked_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_agent_tasks_queue
  on public.agent_tasks(status, priority, due_at, created_at);
create index if not exists idx_agent_tasks_client on public.agent_tasks(client_id, created_at desc);

